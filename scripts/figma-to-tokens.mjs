#!/usr/bin/env node
// Pulls Variables, text styles and effect styles from the open Figma file through the
// figmosha bridge (a Figma plugin + local server, see figmosha2/) and writes tokens.json
// in W3C DTCG format. Run `npm run tokens:sync` to pull and rebuild the CSS.
import { writeFileSync } from "node:fs";

const BRIDGE = process.env.FIGMA_BRIDGE_URL ?? "http://localhost:8787";
const DEFAULT_MODE = process.env.FIGMA_DEFAULT_MODE ?? "Primary";
const OUT = new URL("../tokens.json", import.meta.url);

const READ = `
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const collections = [];
for (const c of cols) {
  const vars = [];
  for (const id of c.variableIds) {
    const v = await figma.variables.getVariableByIdAsync(id);
    if (v) vars.push({ id: v.id, name: v.name, type: v.resolvedType, values: v.valuesByMode, description: v.description });
  }
  collections.push({ name: c.name, modes: c.modes, defaultModeId: c.defaultModeId, vars });
}
const text = (await figma.getLocalTextStylesAsync()).map(s => ({ name: s.name, fontName: s.fontName, fontSize: s.fontSize, lineHeight: s.lineHeight, letterSpacing: s.letterSpacing }));
const effect = (await figma.getLocalEffectStylesAsync()).map(s => ({ name: s.name, effects: s.effects }));
return { file: figma.root.name, collections, text, effect };
`;

const slug = (s) => s.trim().toLowerCase().replace(/\s+/g, "-");
const toHex = ({ r, g, b, a = 1 }) =>
  "#" +
  [r, g, b].map((x) => Math.round(x * 255).toString(16).padStart(2, "0")).join("") +
  (a < 1 ? Math.round(a * 255).toString(16).padStart(2, "0") : "");

function pathFor(collection, name) {
  const parts = name.split("/").map((p) => p.trim());
  // Opacity variables can live in any collection: Opacity/Disabled -> opacity.disabled.
  if (parts[0].toLowerCase() === "opacity") return ["opacity", ...parts.slice(1).map(slug)];
  switch (collection) {
    case "Primitive Colors":
      return ["color", slug(parts[0]), slug(parts[1]).replace(/!$/, "").replace("oapcity", "opacity")];
    case "Primitive Spaces":
      return ["spacing", slug(parts[1]).replace(",", "-")];
    case "Semantic Spaces":
      return [slug(parts[0]), slug(parts[1])];
    case "Semantic Colors":
      return ["color", ...parts.map(slug)];
    default:
      return [slug(collection), ...parts.map(slug)];
  }
}

function setPath(root, path, token) {
  let node = root;
  for (const key of path.slice(0, -1)) node = node[key] ??= {};
  node[path.at(-1)] = token;
}

const WEIGHTS = { thin: 100, extralight: 200, light: 300, regular: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };

const num = (n) => +n.toFixed(4);
const lineHeight = (lh) => (lh.unit === "PERCENT" ? num(lh.value / 100) : lh.unit === "PIXELS" ? `${num(lh.value)}px` : "normal");
const letterSpacing = (ls) => (ls.unit === "PERCENT" ? (ls.value === 0 ? "0px" : `${num(ls.value / 100)}em`) : `${num(ls.value)}px`);

async function main() {
  const res = await fetch(`${BRIDGE}/exec`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ code: READ }),
  }).catch(() => null);
  if (!res) throw new Error(`Bridge not reachable at ${BRIDGE}. Start it and run the Figmosha plugin in Figma.`);
  const body = await res.json();
  if (!body.ok) throw new Error(`Bridge error: ${body.error} ${body.hint ?? ""}`);
  const { file, collections, text, effect } = body.value;

  // First pass: variable id -> token path (aliases can point across collections).
  const idToPath = new Map();
  for (const c of collections) for (const v of c.vars) idToPath.set(v.id, pathFor(c.name, v.name));

  const isOpacity = (path) => path[0] === "opacity";
  const valueOf = (raw, type, path = []) => {
    if (raw && raw.type === "VARIABLE_ALIAS") {
      const p = idToPath.get(raw.id);
      if (!p) throw new Error(`Alias points to a variable outside this file: ${raw.id}`);
      return `{${p.join(".")}}`;
    }
    // Figma stores opacity in percent (60); CSS wants 0-1.
    if (type === "FLOAT" && isOpacity(path)) return raw > 1 ? +(raw / 100).toFixed(4) : raw;
    return type === "COLOR" ? toHex(raw) : type === "FLOAT" ? `${raw}px` : raw;
  };

  const tokens = {
    $description: `Design tokens from the Figma file '${file}'. Generated by scripts/figma-to-tokens.mjs; do not edit by hand.`,
  };

  for (const c of collections) {
    const modeName = new Map(c.modes.map((m) => [m.modeId, m.name]));
    const defaultId = c.modes.find((m) => m.name === DEFAULT_MODE)?.modeId ?? c.defaultModeId;
    for (const v of c.vars) {
      const path = idToPath.get(v.id);
      const type = v.type === "COLOR" ? "color" : isOpacity(path) ? "number" : "dimension";
      const figma = { collection: c.name, variable: v.name };
      if (c.modes.length > 1) {
        figma.defaultMode = modeName.get(defaultId);
        figma.modes = Object.fromEntries(
          c.modes.filter((m) => m.modeId !== defaultId).map((m) => [m.name, valueOf(v.values[m.modeId], v.type, path)]),
        );
      }
      setPath(tokens, path, {
        $type: type,
        $value: valueOf(v.values[defaultId], v.type, path),
        $description: v.description?.trim() || `Figma: ${c.name} / ${v.name}`,
        $extensions: { "com.figma": figma },
      });
    }
  }

  for (const s of text) {
    const segs = s.name.split("/").filter((p) => !/^\d+\s*px$/i.test(p.trim())).map(slug);
    setPath(tokens, ["typography", ...segs], {
      $type: "typography",
      $value: {
        fontFamily: s.fontName.family,
        fontSize: `${s.fontSize}px`,
        fontWeight: WEIGHTS[slug(s.fontName.style)] ?? 400,
        lineHeight: lineHeight(s.lineHeight),
        letterSpacing: letterSpacing(s.letterSpacing),
      },
      $description: `Figma text style: ${s.name}`,
    });
  }

  for (const s of effect) {
    const shadows = s.effects
      .filter((e) => (e.type === "DROP_SHADOW" || e.type === "INNER_SHADOW") && e.visible !== false)
      .map((e) => ({
        color: toHex(e.color),
        offsetX: `${num(e.offset.x)}px`,
        offsetY: `${num(e.offset.y)}px`,
        blur: `${num(e.radius)}px`,
        spread: `${num(e.spread ?? 0)}px`,
        ...(e.type === "INNER_SHADOW" ? { inset: true } : {}),
      }));
    if (!shadows.length) continue;
    const segs = s.name.split("/").map(slug);
    setPath(tokens, ["shadow", ...(segs[0] === "shadow" ? segs.slice(1) : segs)], {
      $type: "shadow",
      $value: shadows.length === 1 ? shadows[0] : shadows,
      $description: `Figma effect style: ${s.name}`,
    });
  }

  writeFileSync(OUT, JSON.stringify(tokens, null, 2) + "\n");
  const count = (o) => Object.values(o).reduce((n, v) => n + (v && typeof v === "object" && "$value" in v ? 1 : v && typeof v === "object" ? count(v) : 0), 0);
  console.log(`Wrote tokens.json from '${file}': ${count(tokens)} tokens.`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
